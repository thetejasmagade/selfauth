#!/usr/bin/env node
/* global process, console */
/* eslint-disable no-console -- script output */
// Generates the committed migration of each database that is derived from the PostgreSQL
// reference (packages/cli/src/dialect.ts): the reference schema is transformed, then Prisma writes
// the SQL for the empty database. `--check` fails when the committed files are out of date.
// Run `pnpm build` first (it needs packages/cli/dist).
import { spawnSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const { adaptSchema } = await import(
  pathToFileURL(join(root, "packages/cli/dist/dialect.js")).href
);

const app = join(root, "apps/playground");
const migrationName = readdirSync(join(app, "prisma/migrations"), { withFileTypes: true }).find(
  (d) => d.isDirectory(),
)?.name;
if (!migrationName) throw new Error("no PostgreSQL migration found to take the name from");
const prisma = join(app, "node_modules/prisma/build/index.js");

let stale = 0;
for (const dialect of ["sqlite"]) {
  // Inside the app, so `prisma/config` resolves from its node_modules (the folder is git-ignored).
  const work = join(app, ".dialect", `sync-${dialect}`);
  rmSync(work, { recursive: true, force: true });
  mkdirSync(work, { recursive: true });
  try {
    mkdirSync(join(work, "prisma"), { recursive: true });
    cpSync(join(app, "prisma.config.ts"), join(work, "prisma.config.ts"));
    writeFileSync(
      join(work, "prisma/schema.prisma"),
      adaptSchema(dialect, readFileSync(join(app, "prisma/schema.prisma"), "utf8")),
    );
    const sqlFile = join(work, "migration.sql");
    const r = spawnSync(
      process.execPath,
      [
        prisma,
        "migrate",
        "diff",
        "--from-empty",
        "--to-schema",
        "prisma/schema.prisma",
        "--script",
        "--output",
        sqlFile,
      ],
      { cwd: work, encoding: "utf8", env: { ...process.env, DATABASE_URL: "" } },
    );
    if (r.status !== 0) throw new Error(r.stderr || r.stdout);
    const expected = new Map([
      [`${migrationName}/migration.sql`, readFileSync(sqlFile, "utf8")],
      [
        "migration_lock.toml",
        `# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "${dialect}"\n`,
      ],
    ]);
    const dir = join(root, "packages/cli/template-variants", dialect, "prisma/migrations");
    const stalePaths = [...expected]
      .filter(
        ([path, content]) =>
          !existsSync(join(dir, path)) || readFileSync(join(dir, path), "utf8") !== content,
      )
      .map(([p]) => p);
    if (!stalePaths.length) continue;
    if (check) {
      console.error(`${dialect} migration is stale: ${stalePaths.join(", ")}`);
      stale++;
      continue;
    }
    rmSync(dir, { recursive: true, force: true });
    for (const [path, content] of expected) {
      mkdirSync(dirname(join(dir, path)), { recursive: true });
      writeFileSync(join(dir, path), content);
    }
    console.log(`wrote ${dialect} migration (${migrationName})`);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}
if (stale) {
  console.error("Run `pnpm templates:sync` (after `pnpm build`).");
  process.exit(1);
}
