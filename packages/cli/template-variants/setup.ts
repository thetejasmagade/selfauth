import express from "express";
import { createAuth, type Auth } from "./auth/index.ts";
import { localDevelopmentConfig } from "./dev-config.ts";
import { loadEnv } from "./env.ts";
import { createMailer } from "./mailer.ts";
import { assignRequestId, getRequestId } from "./request-id.ts";
import { config as baseConfig } from "./selfauth.config.ts";
import { createStores } from "./store.ts";

export interface SelfAuth {
  auth: Auth;
  /** Mount after your routes: renders SelfAuth errors with the spec envelope. */
  errorHandler: express.ErrorRequestHandler;
}

/**
 * Adds SelfAuth to an existing Express app (generated by `selfauth add`).
 *
 *   const selfauth = await setupSelfAuth(app);   // before your routes
 *   app.get("/api/me", selfauth.auth.requireAuth, …);
 *   app.use(selfauth.errorHandler);              // after your routes
 *
 * Session and CSRF middleware apply to the whole app: browsers must send the
 * `X-SelfAuth-CSRF: 1` header on every state-changing request (SEC-CSRF-004).
 */
export async function setupSelfAuth(app: express.Express): Promise<SelfAuth> {
  const env = loadEnv();
  // Plain-http local development cannot use Secure / __Host- cookies.
  const config = env.nodeEnv === "production" ? baseConfig : localDevelopmentConfig(baseConfig);
  const mailer = createMailer(env);
  const { store, rateLimitStore } = await createStores(config);
  const auth = createAuth({
    config,
    store,
    mailer,
    appBaseUrl: env.appBaseUrl,
    nodeEnv: env.nodeEnv,
    requestId: getRequestId,
    ...(rateLimitStore ? { rateLimitStore } : {}),
    ...(env.csrfSecret ? { csrfSecret: env.csrfSecret } : {}),
    ...(env.csrfSecretPrevious ? { csrfSecretPrevious: env.csrfSecretPrevious } : {}),
  });

  app.set("trust proxy", config.http.trustProxy);
  app.use(assignRequestId);
  app.use(config.http.basePath, express.json({ limit: config.http.bodyLimitBytes }));
  app.use(auth.middleware);
  app.use(config.http.basePath, auth.router);
  return { auth, errorHandler: auth.errorHandler };
}
