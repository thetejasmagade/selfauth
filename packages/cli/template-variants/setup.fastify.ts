import type { FastifyError, FastifyInstance, FastifyReply, FastifyRequest } from "fastify";
import { createAuth, type Auth } from "./auth/index.ts";
import { AuthError } from "./auth/core/errors.ts";
import { localDevelopmentConfig } from "./config/dev-config.ts";
import { loadEnv } from "./config/env.ts";
import { createMailer } from "./email/mailer.ts";
import { getRequestId } from "./http/request-id.ts";
import { config as baseConfig } from "./config/selfauth.config.ts";
import { createStores } from "./db/store.ts";

export interface SelfAuth {
  auth: Auth;
  /**
   * `app.setErrorHandler(selfauth.errorHandler)`: renders SelfAuth errors with the spec envelope
   * and hands every other error to Fastify's own handling. If your app already has an error
   * handler, call `selfauth.auth.handleError(error, req, reply)` at its top instead.
   */
  errorHandler: (error: FastifyError, req: FastifyRequest, reply: FastifyReply) => FastifyReply;
}

/**
 * Options Fastify only accepts when the app is created: pass them to `Fastify({ ... })` so the
 * server honours the SelfAuth configuration (SEC-HTTP-003 body limit, SEC-RATE-005 trusted
 * proxies, SEC-LOG-003 request ids that are never read from a header).
 */
export function selfAuthServerOptions() {
  const { http } = baseConfig;
  const trustProxy = http.trustProxy;
  return {
    bodyLimit: http.bodyLimitBytes,
    trustProxy:
      typeof trustProxy === "number"
        ? (_address: string, hop: number) => hop < trustProxy
        : trustProxy,
    requestIdHeader: false as const,
  };
}

/**
 * Adds SelfAuth to an existing Fastify app (generated by `selfauth add`).
 *
 *   const app = Fastify({ ...selfAuthServerOptions() });
 *   const selfauth = await setupSelfAuth(app);        // before your routes
 *   app.get("/api/me", { preHandler: selfauth.auth.requireAuth }, …);
 *   app.setErrorHandler(selfauth.errorHandler);       // or call auth.handleError in yours
 *
 * Session and CSRF hooks apply to the whole app: browsers must send the
 * `X-SelfAuth-CSRF: 1` header on every state-changing request (SEC-CSRF-004).
 */
export async function setupSelfAuth(app: FastifyInstance): Promise<SelfAuth> {
  const env = loadEnv();
  // Plain-http local development cannot use Secure / __Host- cookies.
  const config = env.nodeEnv === "production" ? baseConfig : localDevelopmentConfig(baseConfig);
  const mailer = createMailer(env);
  const { store, rateLimitStore } = await createStores(config);
  const auth = createAuth({
    config,
    store,
    mailer,
    appBaseUrl: env.appBaseUrl,
    nodeEnv: env.nodeEnv,
    requestId: getRequestId,
    ...(rateLimitStore ? { rateLimitStore } : {}),
    ...(env.csrfSecret ? { csrfSecret: env.csrfSecret } : {}),
    ...(env.csrfSecretPrevious ? { csrfSecretPrevious: env.csrfSecretPrevious } : {}),
  });

  // JSON only; an empty body is fine (logout, for example). A malformed one is a 400. Fastify
  // keeps one JSON parser per app: if yours already has a custom one, that one stays.
  try {
    app.addContentTypeParser("application/json", { parseAs: "string" }, (_req, text, done) => {
      if (text === "") return done(null, undefined);
      try {
        done(null, JSON.parse(text as string));
      } catch {
        done(new AuthError("VALIDATION_FAILED", "Malformed JSON body."));
      }
    });
  } catch (error) {
    if ((error as { code?: string }).code !== "FST_ERR_CTP_ALREADY_PRESENT") throw error;
  }

  auth.install(app);
  return {
    auth,
    errorHandler: (error, req, reply) => {
      if (auth.handleError(error, req, reply)) return reply;
      throw error;
    },
  };
}
