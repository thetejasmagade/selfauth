import {
  LEVEL_TITLES,
  type AdapterRecord,
  type CategoryCoverage,
  type Level,
} from "./compliance.js";
import { type ConformanceCase } from "./schema.js";

export interface ConformanceDocInput {
  record: AdapterRecord;
  cases: readonly ConformanceCase[];
  coverage: readonly CategoryCoverage[];
  /** Tested dependency ranges, read from the reference implementation's package.json files. */
  compatibility: readonly { name: string; range: string; note?: string }[];
}

/** Escapes backslashes first, then pipes, so a cell cannot end early or swallow the next one. */
const escape = (text: string) => text.replace(/\\/g, "\\\\").replace(/\|/g, "\\|");
const levelCount = (cases: readonly ConformanceCase[], level: Level) =>
  cases.filter((c) => c.level === level).length;

/**
 * docs/conformance.md. Generated, never hand-edited; apps/playground/test/conformance/report.test.ts
 * fails when the committed copy differs (run it with UPDATE_CONFORMANCE_DOC=1 to rewrite it).
 */
export function renderConformanceDoc({
  record,
  cases,
  coverage,
  compatibility,
}: ConformanceDocInput): string {
  const lines: string[] = [];
  const out = (...l: string[]) => lines.push(...l);

  out(
    "<!-- Generated by apps/playground/test/conformance/report.test.ts from conformance/adapters/express.json. Do not edit. -->",
    "",
    "# Conformance and support matrix",
    "",
    `What the SelfAuth ${record.title} is tested against, which compliance level each`,
    `store reaches, and what is not supported. Specification version: **${record.specVersion}**.`,
    "",
    "A generator that runs is not a conformant adapter. A level is claimed only",
    "when the cases for it pass in CI and every non-case requirement has a recorded",
    "sign-off with evidence (`conformance/adapters/express.json`).",
    "",
    "## Compliance levels",
    "",
    "| Level | Needs | Cases |",
    "| --- | --- | --- |",
    `| ${LEVEL_TITLES.core} | all core cases pass; every automated check for core requirements (adapter, schema, migration tests) is signed off | ${levelCount(cases, "core")} |`,
    `| ${LEVEL_TITLES.authorization} | core, plus the authorization cases and the authorization checks | ${levelCount(cases, "authorization")} |`,
    `| ${LEVEL_TITLES.production} | all cases, plus every review, documentation and static-analysis item signed off | ${levelCount(cases, "production")} |`,
    "",
    `The suite has ${cases.length} cases in total.`,
    "",
    "## Result",
    "",
    "| Store | Published level |",
    "| --- | --- |",
    ...Object.entries(record.claims)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([store, level]) => `| ${store} | ${LEVEL_TITLES[level]} |`),
    "",
    record.independentAudit
      ? "The code has been audited by an independent party."
      : "**No independent security audit has been done.** Production-profile status is self-assessed from the sign-offs below. An outside review is required before 1.0.",
    "",
    "CI runs the whole suite against the in-memory store and against PostgreSQL, and fails if either measures below its published level.",
    "",
    "## Support matrix",
    "",
    "| Kind | Supported | Notes |",
    "| --- | --- | --- |",
    ...record.supports.map(
      (s) => `| ${s.kind} | \`${s.id}\` | ${s.title}${s.store ? ` (store \`${s.store}\`)` : ""} |`,
    ),
    "",
    "Not supported yet: see [Known limitations](#known-limitations).",
    "",
    "## Version compatibility",
    "",
    "| Component | Tested range | Notes |",
    "| --- | --- | --- |",
    ...compatibility.map((c) => `| ${c.name} | \`${c.range}\` | ${c.note ?? ""} |`),
    "",
    "## Coverage by area",
    "",
    "| Area | Mandatory requirements | By cases | By other checks | Cases touching it |",
    "| --- | ---: | ---: | ---: | ---: |",
    ...coverage.map(
      (c) =>
        `| ${c.category.title} | ${c.mandatory} | ${c.byCases} | ${c.byOtherVerification} | ${c.cases} |`,
    ),
    "",
    "Every mandatory requirement is covered by a case or by another check; the build fails otherwise.",
    "",
    "## Known limitations",
    "",
    ...record.limitations.map((l) => `- ${l}`),
    "",
    "## Sign-offs",
    "",
    "Requirements proven by something other than a conformance case, and how.",
    "",
    "| Requirement | Method | Finding | Evidence |",
    "| --- | --- | --- | --- |",
    ...record.signoffs.map(
      (s) =>
        `| ${s.requirement} | ${s.method} | ${escape(s.finding)} | ${s.evidence.map((e) => `\`${e}\``).join(", ")} |`,
    ),
    "",
    "## Reproduce",
    "",
    "```bash",
    "pnpm build",
    "pnpm --filter @selfauth/conformance coverage:report",
    "pnpm --filter @selfauth/playground test        # runs every case; set TEST_DATABASE_URL for PostgreSQL",
    "```",
    "",
  );
  return lines.join("\n");
}
